"""
Central app configuration. Everything here is overridable via a .env file
(see .env.example) or real environment variables — nothing is hardcoded so
this runs unchanged in local dev, Docker, or a real deployment.
"""
from functools import lru_cache
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", extra="ignore")

    # --- App ---
    APP_NAME: str = "LINEAGE API"
    ENV: str = "development"
    DEBUG: bool = True

    # --- Database ---
    # Defaults to a local SQLite file so `uvicorn app.main:app` works with zero
    # setup. Per the TRD, SQLite is an accepted stand-in for Postgres during
    # early development — set DATABASE_URL to a real Postgres DSN
    # (postgresql+psycopg2://user:pass@host:5432/lineage) for anything beyond
    # a single developer's machine.
    DATABASE_URL: str = "sqlite:///./data/lineage.db"

    # --- Auth ---
    # Generate a real secret for anything beyond local dev:
    #   python -c "import secrets; print(secrets.token_hex(32))"
    JWT_SECRET_KEY: str = "dev-only-secret-change-me"
    JWT_ALGORITHM: str = "HS256"
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 15
    REFRESH_TOKEN_EXPIRE_DAYS: int = 7
    AUTH_COOKIE_SECURE: bool = False
    AUTH_COOKIE_SAMESITE: str = "lax"

    # Load the ML models when the server starts instead of on the first
    # request. Costs a few seconds of startup time but avoids a slow (and
    # previously contended) first upload. Set false for fast dev restarts.
    PRELOAD_MODELS: bool = True

    # --- LLM report generation (optional) ---
    # If set, the Incident Report's summary paragraph is generated by a real
    # LLM call using the structured evidence as input (TRD §5.4). If left
    # blank, a deterministic template (app/services/report_builder.py)
    # produces the summary instead — the report's JSON *schema* is identical
    # either way; only the summary's prose source changes.
    ANTHROPIC_API_KEY: str = ""
    ANTHROPIC_MODEL: str = "claude-sonnet-4-5"

    # --- Image-led public web discovery (optional) ---
    GEMINI_API_KEY: str = ""
    GEMINI_SEARCH_MODEL: str = "gemini-3.8-flash"
    MAX_WEB_SEARCHES_PER_MEDIA: int = 3
    DETECTOR_MODEL_ID: str = "dima806/deepfake_vs_real_image_detection"
    DETECTOR_SECOND_MODEL_ID: str = ""
    DETECTOR_EVAL_THRESHOLD: float = 50.0
    DETECTOR_VIDEO_FRAME_COUNT: int = 12
    # Where the evaluation CLI writes its report and the Detector panel reads it from.
    EVAL_RESULTS_PATH: str = "eval/results/latest.json"
    # Set true when running without internet (models must already be cached). Shown in /health and the UI.
    OFFLINE_DEMO_MODE: bool = False
    AUDIO_DEEPFAKE_MODEL_ID: str = ""
    REVERSE_SEARCH_PROVIDER: str = "none"
    GOOGLE_CLOUD_PROJECT: str = ""
    AUDIO_EXTRACTION_TIMEOUT_SECONDS: int = 20

    # --- Phase 3A: Neo4j graph persistence (optional) ---
    # Leave NEO4J_URI blank to run without Neo4j: every graph endpoint then
    # serves the in-memory KnowledgeGraph (the Phase 3A behaviour). These are
    # backend-only settings and are never sent to the frontend.
    NEO4J_URI: str = ""                  # e.g. bolt://localhost:7687 (neo4j:// for clusters)
    NEO4J_USER: str = "neo4j"
    NEO4J_PASSWORD: str = ""
    NEO4J_DATABASE: str = "neo4j"
    NEO4J_CONNECT_TIMEOUT: float = 3.0   # seconds; keeps the fallback fast when Neo4j is down
    NEO4J_RETRY_SECONDS: float = 30.0    # after a failed connection, wait this long before retrying
    # When true, reading an investigation's graph first re-syncs it (idempotent MERGE) so Neo4j
    # never serves a stale view of the SQL records. Set false to only sync via the sync endpoint/CLI.
    NEO4J_AUTO_SYNC: bool = True

    # --- Phase 3B: Investigation Copilot (Graph RAG) ---
    # "anthropic" uses ANTHROPIC_API_KEY; "none" disables the LLM. With no LLM (or no key) the
    # Copilot still answers from the retrieved graph/evidence using a deterministic composer.
    COPILOT_LLM_PROVIDER: str = "anthropic"
    COPILOT_MODEL: str = "claude-opus-5-5"
    COPILOT_MAX_TOKENS: int = 4000

    # --- Phase 4: ML Intelligence (local, deterministic; all thresholds explainable) ---
    ML_SIMILARITY_THRESHOLD: float = 0.75       # min perceptual-hash similarity (0-1) to report a pair
    ML_CLUSTER_THRESHOLD: float = 0.85          # single-linkage edge threshold for clustering
    ML_ANOMALY_MIN_OBSERVATIONS: int = 4        # timed observations needed to establish a baseline interval
    ML_ANOMALY_MIN_RELATIONSHIPS: int = 3       # timed relationships needed for a propagation-timing baseline
    ML_BURST_RATIO: float = 0.25                # interval < ratio x median interval counts as unusually fast
    ML_GEO_SPREAD_KM: float = 500.0             # max distance between >=3 locations inside one normal interval

    # --- File storage ---
    DATA_DIR: str = "./data"
    UPLOADS_DIR: str = "./data/uploads"
    MAX_UPLOAD_MB: int = 500
    # Content sniffing of uploads: enforce (refuse), log (record what would be refused), off.
    UPLOAD_SNIFF_MODE: str = "enforce"
    # true = also refuse audio/video whose container signature is not recognised (default: accept, flag unverified).
    UPLOAD_SNIFF_STRICT_AV: bool = False
    RATE_LIMIT_LOGIN_PER_MINUTE: int = 8
    RATE_LIMIT_UPLOAD_PER_MINUTE: int = 12
    RATE_LIMIT_TRACE_PER_MINUTE: int = 6
    RATE_LIMIT_COPILOT_PER_MINUTE: int = 20
    REDIS_URL: str = ""
    MAX_REQUEST_BODY_MB: int = 550
    REQUIRE_REVIEW_FOR_SENSITIVE_ACTIONS: bool = True
    FACE_SIMILARITY_REVIEW_THRESHOLD: float = 85.0
    DATA_RETENTION_DAYS: int = 30
    TRACE_MAX_IMAGES: int = 12
    TRACE_IMAGE_TIMEOUT_SECONDS: float = 5.0
    TRACE_MAX_SECONDS: float = 30.0
    # Crop-robust local-feature verification (ORB + RANSAC) for candidates the whole-image hashes miss.
    TRACE_FEATURE_MATCH_ENABLED: bool = True
    TRACE_USE_HEADLESS_BROWSER: bool = False
    TRACE_BROWSER_TIMEOUT_SECONDS: int = 12

    # Symmetric key used to encrypt uploaded files at rest (Fernet/AES-128).
    # Generate a real one with:
    #   python -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"
    # If left as the placeholder, the app will generate and persist one on
    # first run (dev convenience) — but a real deployment must set this
    # explicitly so restarts don't orphan already-encrypted files.
    FILE_ENCRYPTION_KEY: str = ""
    KEY_PROVIDER: str = "env"  # current implementation: env; AWS/Azure secrets-manager integration planned
    KEY_ID: str = ""
    FILE_ENCRYPTION_KEY_PREVIOUS: str = ""

    # --- Phase 5: production persistence / jobs / object storage ---
    STORAGE_BACKEND: str = "local"  # local | s3
    S3_BUCKET: str = ""
    S3_PREFIX: str = "lineage"
    S3_REGION: str = ""
    S3_ENDPOINT_URL: str = ""
    S3_ACCESS_KEY_ID: str = ""
    S3_SECRET_ACCESS_KEY: str = ""
    JOB_QUEUE_ENABLED: bool = False
    JOB_POLL_SECONDS: float = 2.0
    RETENTION_PURGE_ENABLED: bool = False
    RETENTION_PURGE_INTERVAL_HOURS: int = 24
    REQUIRE_DATABASE_MIGRATIONS: bool = False

    # --- Phase 6: trust, privacy and support ---
    LEGAL_REVIEW_STATUS: str = "pending"
    # Template version counsel actually reviewed. Approval only counts while this equals BSA_CERTIFICATE_TEMPLATE_VERSION,
    # so editing the template silently un-approves it.
    LEGAL_REVIEWED_TEMPLATE_VERSION: str = ""
    PRIVACY_POLICY_VERSION: str = "2026-10-02"
    BSA_CERTIFICATE_TEMPLATE_VERSION: str = "1.0"
    VICTIM_SUPPORT_URL: str = "https://www.cybercrime.gov.in/"
    SUPPORT_EMAIL: str = ""

    # --- Phase E: evidence and legal depth ---
    # Ed25519 key that signs integrity manifests. Accepts a base64 32-byte seed or a PEM private key.
    # Outside development/test this MUST be supplied by the deployment secret manager; in development a
    # key is generated once and persisted next to the file-encryption key.
    MANIFEST_SIGNING_KEY: str = ""
    # Optional RFC 3161 Time-Stamp Authority. Blank = manifests are signed but not independently timestamped.
    # Use a TSA you have chosen and reviewed (e.g. a national/commercial TSA); nothing is sent unless this is set.
    MANIFEST_TSA_URL: str = ""
    MANIFEST_TSA_TIMEOUT_SECONDS: float = 10.0
    # Scheduled sweep of abandoned page captures (trace results nobody accepted or rejected).
    CAPTURE_SWEEP_ENABLED: bool = False
    CAPTURE_SWEEP_INTERVAL_HOURS: int = 6
    # Must exceed the 30-minute pending-match lifetime plus any in-flight upload; never set below 1 hour.
    CAPTURE_SWEEP_GRACE_MINUTES: int = 120

    # --- Metadata forensics, origin and hosting enrichment ---
    # ModifyDate may trail DateTimeOriginal by this many seconds before the file is flagged as saved after capture.
    METADATA_DATE_GAP_SECONDS: int = 300
    # Off by default: RDAP lookups contact a third party (it learns the server IP / domain of a traced page; no case media or facts).
    HOSTING_RDAP_ENABLED: bool = False
    HOSTING_RDAP_BASE: str = "https://rdap.org"
    HOSTING_RDAP_TIMEOUT_SECONDS: float = 5.0

    # --- Security additions ---
    # Upload malware scan: off | log (record only; the default) | enforce (refuse; production compose sets this). Uses ClamAV (clamd) when CLAMD_HOST is set; the built-in
    # EICAR test-signature check always runs when the mode is not "off".
    MALWARE_SCAN_MODE: str = "log"
    CLAMD_HOST: str = ""
    CLAMD_PORT: int = 3310
    CLAMD_TIMEOUT_SECONDS: float = 15.0
    # Refuse images whose decoded size would exceed this many pixels (decompression-bomb guard). 0 = disabled.
    MAX_IMAGE_PIXELS: int = 100_000_000
    MAX_VIDEO_FRAMES: int = 1200
    MAX_VIDEO_DURATION_SECONDS: int = 600
    MAX_DECOMPRESSION_RATIO: float = 250.0
    DECOMPRESSION_RATIO_MIN_PIXELS: int = 20_000_000  # ratio check applies only at or above this many pixels
    UPLOAD_PROBE_TIMEOUT_SECONDS: int = 20
    ADMIN_EMAILS: str = ""
    # Hash-chain every new audit event so after-the-fact edits or deletions are detectable.
    AUDIT_CHAIN_ENABLED: bool = True
    MFA_ISSUER: str = "LINEAGE"
    # Redact emails, phone numbers and ID-like numbers from case text before it is sent to an external model.
    PROMPT_REDACT_PII: bool = True
    # Second factor. MFA_REQUIRED=true lets users log in but blocks every route except /auth/* until they enrol.
    # MFA_ENCRYPTION_KEY (a Fernet key) encrypts TOTP secrets in the database; required when ENV is not development/test.
    MFA_REQUIRED: bool = False
    MFA_ENCRYPTION_KEY: str = ""
    MFA_RECOVERY_CODE_COUNT: int = 10

    # --- CORS ---
    # The Vite dev server's default origin. Add your deployed frontend's
    # origin here (comma-separated) once you have one.
    CORS_ORIGINS: str = "http://localhost:5173,http://127.0.0.1:5173,http://localhost:5174,http://127.0.0.1:5174"

    @property
    def cors_origins_list(self) -> list[str]:
        return [o.strip() for o in self.CORS_ORIGINS.split(",") if o.strip()]


@lru_cache
def get_settings() -> Settings:
    return Settings()
